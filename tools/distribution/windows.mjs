const exec = promisify(execFile);

function nsVersion(version) {
  const [major = 0, minor = 0, patch = 0] = version.replace(/-.*$/, "").split(".").map(Number);
  return `${major}.${minor}.${patch}.0`;
}

function quote(value) {
  return `"${value.replace(/"/g, '""')}"`;
}

function nsisScript({ version, sourceDirectory, output, icon }) {
  return `; Generated by tools/distribution/windows.mjs. Do not edit by hand.
Unicode true
!include "MUI2.nsh"

!define APP_NAME ${quote(PRODUCT.name)}
!define APP_VERSION ${quote(version)}
!define APP_EXE "Audivane.exe"
!define APP_SOURCE ${quote(sourceDirectory)}
!define APP_ICON ${quote(icon)}
!define APP_MARKER ".audivane-install"
!define APP_UNINSTALL_KEY "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\Audivane"

Name "\${APP_NAME}"
OutFile ${quote(output)}
; Per-user, fixed location. No directory page: an installer must never run
; RMDir /r against an arbitrary user-selected directory.
InstallDir "$LOCALAPPDATA\\Programs\\Audivane"
RequestExecutionLevel user
SetCompressor /SOLID zlib
BrandingText "\${APP_NAME} \${APP_VERSION}"

VIProductVersion ${quote(nsVersion(version))}
VIAddVersionKey "ProductName" "\${APP_NAME}"
VIAddVersionKey "FileDescription" "\${APP_NAME} installer"
VIAddVersionKey "FileVersion" "\${APP_VERSION}"
VIAddVersionKey "ProductVersion" "\${APP_VERSION}"
VIAddVersionKey "LegalCopyright" "Copyright 2026 Triet (@Triet1402)"

!define MUI_ABORTWARNING
!define MUI_ICON "\${APP_ICON}"
!define MUI_UNICON "\${APP_ICON}"
!define MUI_FINISHPAGE_RUN
!define MUI_FINISHPAGE_RUN_FUNCTION LaunchAudivane
!define MUI_FINISHPAGE_RUN_TEXT "Launch \${APP_NAME}"

!insertmacro MUI_PAGE_WELCOME
!insertmacro MUI_PAGE_INSTFILES
!insertmacro MUI_PAGE_FINISH
!insertmacro MUI_UNPAGE_CONFIRM
!insertmacro MUI_UNPAGE_INSTFILES
!insertmacro MUI_LANGUAGE "English"

Function LaunchAudivane
  Exec '"$INSTDIR\\\${APP_EXE}"'
FunctionEnd

Section "Install"
  SetShellVarContext current
  StrCpy $INSTDIR "$LOCALAPPDATA\\Programs\\Audivane"

  ; Refuse an existing directory we do not own. This prevents an upgrade from
  ; deleting unrelated files if a user or another product occupied the path.
  IfFileExists "$INSTDIR" 0 install
    IfFileExists "$INSTDIR\\\${APP_MARKER}" 0 foreign
    ClearErrors
    FileOpen $0 "$INSTDIR\\\${APP_MARKER}" r
    IfErrors foreign
    FileRead $0 $1
    FileClose $0
    StrCmp $1 "\${APP_NAME}" install foreign
  foreign:
    MessageBox MB_OK|MB_ICONSTOP "\${APP_NAME} will not replace an existing directory it does not own:$\\r$\\n$INSTDIR$\\r$\\n$\\r$\\nMove or remove that directory first." /SD IDOK
    SetErrorLevel 2
    Abort

  install:
  ; Stage the complete new tree beside the old one so a copy failure cannot
  ; leave a mixed installation.
  IfFileExists "$INSTDIR.installing" 0 stage
    IfFileExists "$INSTDIR.installing\\\${APP_MARKER}" stage
    MessageBox MB_OK|MB_ICONSTOP "\${APP_NAME} found an unfinished installation it does not own:$\\r$\\n$INSTDIR.installing" /SD IDOK
    SetErrorLevel 2
    Abort
  stage:
  RMDir /r "$INSTDIR.installing"
  IfFileExists "$INSTDIR.installing" 0 stage-ready
    MessageBox MB_OK|MB_ICONSTOP "\${APP_NAME} could not remove its previous staging directory. Close \${APP_NAME} and any Explorer window using it, then run the installer again." /SD IDOK
    SetErrorLevel 3
    Abort
  stage-ready:
  ClearErrors
  SetOutPath "$INSTDIR.installing"
  IfErrors copyfail
  FileOpen $0 "$INSTDIR.installing\\\${APP_MARKER}" w
  IfErrors copyfail
  FileWrite $0 "\${APP_NAME}"
  FileClose $0
  File /r "\${APP_SOURCE}\\*"
  IfErrors copyfail
  IfFileExists "$INSTDIR.installing\\\${APP_EXE}" 0 copyfail
  IfFileExists "$INSTDIR.installing\\resources\\distribution.json" 0 copyfail

  ; Release the staging current directory before renaming or deleting it.
  SetOutPath "$TEMP"

  ; Remove the old tree only after the staged tree is complete. A locked or
  ; partially deleted old tree aborts the upgrade and preserves the retry
  ; marker instead of silently continuing with stale files.
  IfFileExists "$INSTDIR" 0 swap
    ClearErrors
    RMDir /r "$INSTDIR"
    IfFileExists "$INSTDIR" 0 swap
      ; Recreate ownership metadata (a partial removal may have deleted it) and
      ; fail without touching the staged tree or registry.
      ClearErrors
      FileOpen $0 "$INSTDIR\\\${APP_MARKER}" w
      IfErrors marker-not-written
      FileWrite $0 "\${APP_NAME}"
      FileClose $0
      marker-not-written:
      MessageBox MB_OK|MB_ICONSTOP "\${APP_NAME} could not remove the previous installation. Close \${APP_NAME} and any Explorer window using it, then run the installer again." /SD IDOK
      SetErrorLevel 3
      Abort

  swap:
  ClearErrors
  Rename "$INSTDIR.installing" "$INSTDIR"
  IfErrors swapfail

  CreateDirectory "$SMPROGRAMS\\\${APP_NAME}"
  CreateShortcut "$SMPROGRAMS\\\${APP_NAME}\\\${APP_NAME}.lnk" "$INSTDIR\\\${APP_EXE}"
  CreateShortCut "$DESKTOP\\\${APP_NAME}.lnk" "$INSTDIR\\\${APP_EXE}"
  WriteUninstaller "$INSTDIR\\Uninstall.exe"
  WriteRegStr HKCU "Software\\Audivane" "InstallDir" "$INSTDIR"
  WriteRegStr HKCU "\${APP_UNINSTALL_KEY}" "DisplayName" "\${APP_NAME}"
  WriteRegStr HKCU "\${APP_UNINSTALL_KEY}" "DisplayVersion" "\${APP_VERSION}"
  WriteRegStr HKCU "\${APP_UNINSTALL_KEY}" "DisplayIcon" "$\\"$INSTDIR\\\${APP_EXE}$\\""
  WriteRegStr HKCU "\${APP_UNINSTALL_KEY}" "Publisher" "\${APP_NAME}"
  WriteRegStr HKCU "\${APP_UNINSTALL_KEY}" "InstallLocation" "$\\"$INSTDIR$\\""
  WriteRegStr HKCU "\${APP_UNINSTALL_KEY}" "UninstallString" "$\\"$INSTDIR\\Uninstall.exe$\\""
  WriteRegStr HKCU "\${APP_UNINSTALL_KEY}" "QuietUninstallString" "$\\"$INSTDIR\\Uninstall.exe$\\" /S"
  WriteRegDWORD HKCU "\${APP_UNINSTALL_KEY}" "NoModify" 1
  WriteRegDWORD HKCU "\${APP_UNINSTALL_KEY}" "NoRepair" 1
  WriteRegDWORD HKCU "\${APP_UNINSTALL_KEY}" "EstimatedSize" 380000
  Goto installed

  copyfail:
    SetOutPath "$TEMP"
    RMDir /r "$INSTDIR.installing"
    MessageBox MB_OK|MB_ICONSTOP "\${APP_NAME} could not copy a complete installation. Check free disk space and permissions, then run the installer again." /SD IDOK
    SetErrorLevel 4
    Abort

  swapfail:
    MessageBox MB_OK|MB_ICONSTOP "\${APP_NAME} could not activate the staged installation. The staged installation was retained for retry. Close \${APP_NAME} and run the installer again." /SD IDOK
    SetErrorLevel 5
    Abort

  installed:
SectionEnd

Section "Uninstall"
  SetShellVarContext current
  SetOutPath "$TEMP"
  ; Ignore a tampered registry path: the uninstaller only owns this fixed
  ; per-user directory and its marker.
  StrCpy $INSTDIR "$LOCALAPPDATA\\Programs\\Audivane"
  IfFileExists "$INSTDIR\\\${APP_MARKER}" 0 not-ours
  ClearErrors
  RMDir /r "$INSTDIR"
  IfFileExists "$INSTDIR" 0 removed
  ; Preserve ownership so a later retry can finish once the lock is released.
  ClearErrors
  FileOpen $0 "$INSTDIR\\\${APP_MARKER}" w
  IfErrors uninstall-marker-not-written
  FileWrite $0 "\${APP_NAME}"
  FileClose $0
  uninstall-marker-not-written:
  MessageBox MB_OK|MB_ICONSTOP "\${APP_NAME} could not be completely removed. Close \${APP_NAME} and any Explorer window using $INSTDIR, then run the uninstaller again." /SD IDOK
  SetErrorLevel 6
  Abort

  not-ours:
    MessageBox MB_OK|MB_ICONSTOP "\${APP_NAME} is not installed at $INSTDIR (ownership marker missing). Nothing was deleted." /SD IDOK
    SetErrorLevel 7
    Abort

  removed:
  Delete "$DESKTOP\\\${APP_NAME}.lnk"
  Delete "$SMPROGRAMS\\\${APP_NAME}\\\${APP_NAME}.lnk"
  RMDir "$SMPROGRAMS\\\${APP_NAME}"
  DeleteRegKey HKCU "\${APP_UNINSTALL_KEY}"
  DeleteRegKey HKCU "Software\\Audivane"
SectionEnd
`;
}

async function findMakensis() {
  if (process.env.MAKENSIS) return process.env.MAKENSIS;
  const candidates = [];
  if (process.platform === "win32") {
    for (const base of [process.env.ProgramFiles, process.env["ProgramFiles(x86)"]]) {
      if (base) candidates.push(path.join(base, "NSIS", "makensis.exe"));
    }
  }
  for (const candidate of candidates) {
    if (await fs.access(candidate).then(() => true, () => false)) return candidate;
  }
  return null;
}

export async function buildWindowsArtifacts(options = {}) {
  const packagedDirectory = path.resolve(options.packagedDirectory ?? path.join(root, "dist/desktop/Audivane-win32-x64"));
  const workspace = JSON.parse(await fs.readFile(path.join(root, "package.json"), "utf8"));
  const distribution = JSON.parse(await fs.readFile(path.join(packagedDirectory, "resources/distribution.json"), "utf8"));
  if (distribution.version !== workspace.version) throw new Error("Packaged desktop version disagrees with the workspace manifest");
  if (distribution.platform !== "win32") throw new Error("Windows artifacts require a win32 packaged application");
  if (distribution.nativeBundle?.mode !== "portable-native-bundle-v1") {
    throw new Error("Refusing Windows distribution artifacts without the explicit provenance-controlled native bundle");
  }
  if (distribution.processHost === null || typeof distribution.processHost !== "object" ||
      distribution.processHost.path !== "process-host/audivane-process-host.exe" ||
      typeof distribution.processHost.sha256 !== "string" ||
      !Number.isSafeInteger(distribution.processHost.bytes) ||
      distribution.processHost.bytes <= 0) {
    throw new Error("Refusing Windows distribution artifacts without the whole-desktop process lifetime host");
  }
  const processHostPath = path.join(packagedDirectory, "resources", "process-host", "audivane-process-host.exe");
  const processHostBytes = await fs.readFile(processHostPath);
  if (processHostBytes.length !== distribution.processHost.bytes) {
    throw new Error("Packaged process lifetime host size disagrees with distribution metadata");
  }
  if (createHash("sha256").update(processHostBytes).digest("hex") !== distribution.processHost.sha256) {
    throw new Error("Packaged process lifetime host hash disagrees with distribution metadata");
  }
  const version = workspace.version;
  const outputDirectory = path.resolve(options.outputDirectory ?? releaseDirectory());
  await fs.mkdir(outputDirectory, { recursive: true });
  const zipPath = path.join(outputDirectory, windowsZipFilename(version));
  const zip = await writeZipFromDirectory(packagedDirectory, zipPath, { jobs: options.jobs, signal: options.signal });
  const scriptPath = path.resolve(options.scriptPath ?? path.join(root, "build/nsis/audivane.nsi"));
  const installerPath = path.join(outputDirectory, windowsInstallerFilename(version));
  // Always write the installer contract, including with --no-installer and when
  // makensis is unavailable. CI and verifyNsisScript inspect this exact script.
  await fs.mkdir(path.dirname(scriptPath), { recursive: true });
  await fs.writeFile(scriptPath, nsisScript({
    version,
    sourceDirectory: packagedDirectory,
    output: installerPath,
    icon: path.join(root, ICONS.ico),
  }));
  const makensis = await findMakensis();
  if (!makensis && options.requireInstaller !== false) {
    throw new Error(`NSIS makensis was not found; the .nsi contract was written to ${scriptPath}. Set MAKENSIS to the explicit executable path; the portable ZIP was produced.`);
  }
  let installer = null;
  if (makensis) {
    await fs.rm(installerPath, { force: true });
    await exec(makensis, [process.platform === "win32" ? "/V2" : "-V2", scriptPath], { env: { ...process.env, LC_ALL: "C.UTF-8" }, maxBuffer: 64 * 1024 * 1024 });
    const bytes = await fs.readFile(installerPath);
    installer = Object.freeze({ path: installerPath, size: bytes.length, sha256: createHash("sha256").update(bytes).digest("hex") });
  }
  return Object.freeze({ zip, installer, scriptPath, makensis });
}

